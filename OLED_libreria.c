void I2C_Init(void) {
    TRISBbits.TRISB1 = 1;   /* SCL */
    TRISBbits.TRISB0 = 1;   /* SDA */
    SSPSTAT  = 0x80;
    SSPCON1  = 0x28;
    SSPCON2  = 0x00;
    SSPADD   = I2C_BAUDRATE;
    PIR1bits.SSPIF = 0;
}

void I2C_Ready(void) {
    while (SSPSTATbits.BF || (SSPCON2 & 0x1F));
    __delay_us(5);
}

unsigned char I2C_Start(unsigned char addr) {
    I2C_Ready();
    SSPCON2bits.SEN = 1;
    while (SSPCON2bits.SEN);
    SSPBUF = addr;
    while (!PIR1bits.SSPIF);
    PIR1bits.SSPIF = 0;
    return SSPCON2bits.ACKSTAT;
}

unsigned char I2C_Write(unsigned char data) {
    I2C_Ready();
    SSPBUF = data;
    while (!PIR1bits.SSPIF);
    PIR1bits.SSPIF = 0;
    return SSPCON2bits.ACKSTAT;
}

void I2C_Stop(void) {
    I2C_Ready();
    SSPCON2bits.PEN = 1;
    while (SSPCON2bits.PEN);
    PIR1bits.SSPIF = 0;
}

void OLED_Comando(unsigned char cmd) {
    I2C_Start(OLED_ADDR);
    I2C_Write(OLED_CMD);
    I2C_Write(cmd);
    I2C_Stop();
}

void OLED_Dato(unsigned char dato) {
    I2C_Start(OLED_ADDR);
    I2C_Write(OLED_DATA);
    I2C_Write(dato);
    I2C_Stop();
}

void OLED_Clear(void) {
    unsigned char pagina, col;
    for (pagina = 0; pagina < OLED_PAGES; pagina++) {
        OLED_Comando(0xB0 | pagina);
        OLED_Comando(0x00);
        OLED_Comando(0x10);
        for (col = 0; col < OLED_WIDTH; col++) {
            OLED_Dato(0x00);
        }
    }
}

void OLED_SetCursor(unsigned char pagina, unsigned char col) {
    col += 2; /* Offset de 2px hacia la zona visible */
    OLED_Comando(0xB0 + pagina);
    OLED_Comando(0x00 + (col & 0x0F));
    OLED_Comando(0x10 + ((col >> 4) & 0x0F));
}

