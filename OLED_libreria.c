void OLED_Char(unsigned char c) {
    unsigned char i;
    if (c < 32 || c > 126) c = 32;
    for (i = 0; i < 5; i++) {
        OLED_Dato(font5x8[c - 32][i]);
    }
    OLED_Dato(0x00);
}

void OLED_String(unsigned char pagina, unsigned char col, const char *texto) {
    OLED_SetCursor(pagina, col);
    while (*texto != '\0') {
        OLED_Char((unsigned char)*texto);
        texto++;
    }
}

void OLED_Int(unsigned char pagina, unsigned char col, unsigned int valor) {
    char buffer[6];
    unsigned char i = 0, j;
    char temp;

    if (valor == 0) {
        OLED_String(pagina, col, "0");
        return;
    }
    while (valor > 0) {
        buffer[i++] = '0' + (valor % 10);
        valor /= 10;
    }
    buffer[i] = '\0';
    for (j = 0; j < i / 2; j++) {
        temp = buffer[j];
        buffer[j] = buffer[i - 1 - j];
        buffer[i - 1 - j] = temp;
    }
    OLED_String(pagina, col, buffer);
}

void OLED_BorrarTexto(unsigned char pagina, unsigned char col,
                      unsigned char longitud) {
    unsigned char i;
    OLED_SetCursor(pagina, col);
    for (i = 0; i < longitud; i++) {
        OLED_Char(' ');
    }
}
